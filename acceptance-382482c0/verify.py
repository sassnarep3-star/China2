#!/usr/bin/env python3
"""Structural, citation and cost-ledger checks for the corrective integration."""
import csv
import os
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
failures = []
checks = 0

def check(condition, message):
    global checks
    checks += 1
    if not condition:
        failures.append(message)

class Page(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids = set()
        self.links = []
        self.rows = []
        self.in_row = False
        self.row = []
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if "id" in a:
            self.ids.add(a["id"])
        if tag == "a" and "href" in a:
            self.links.append(a["href"])
        if tag == "tr":
            self.in_row = True
            self.row = []
        if self.in_row:
            self.row.append((tag, a))
    def handle_endtag(self, tag):
        if tag == "tr" and self.in_row:
            self.rows.append(self.row)
            self.in_row = False
            self.row = []

def parse(path):
    p = Page()
    p.feed(path.read_text(encoding="utf-8"))
    return p

page_path = HERE / "index.html"
check(page_path.exists(), "acceptance page missing")
html = page_path.read_text(encoding="utf-8")
p = parse(page_path)
check(html.startswith("<!doctype html>"), "doctype missing")
check('<html lang="en">' in html, "language missing")
check('<meta name="viewport"' in html, "mobile viewport missing")
check(html.count("<main") == 1, "expected one main")
data_rows = [row for row in p.rows if any(tag == "td" for tag, _ in row)]
check(len(data_rows) == 15, f"expected 8 findings + 7 flags, got {len(data_rows)}")
allowed = ("safe.gov.cn", "irs.gov", "govinfo.gov", "boc.cn", "chinatax.gov.cn")
for n, row in enumerate(data_rows, 1):
    hrefs = [a.get("href", "") for tag, a in row if tag == "a"]
    check(any(h.startswith("https://") and any(host in h for host in allowed) for h in hrefs),
          f"row {n} lacks a direct primary-source link")
for expected in [f"V{i:02d}" for i in range(1, 9)] + [f"F{i:02d}" for i in range(1, 8)]:
    check(expected in p.ids, f"missing ledger anchor {expected}")
check("Blank —" in html, "blank/unverified policy not visible")
check("needs review" in html, "needs-review status not visible")
check("not a fresh legal certification" in html, "targeted-review boundary missing")

# Internal links and fragments on this page and the corrected landing page.
pages = [page_path, ROOT / "index.html"]
for source in pages:
    parsed = parse(source)
    for href in parsed.links:
        if href.startswith(("https://", "http://", "mailto:", "data:", "javascript:")):
            continue
        path_part, _, fragment = href.partition("#")
        target = source if not path_part else (source.parent / path_part).resolve()
        check(target.exists(), f"broken local link in {source.name}: {href}")
        if fragment and target.exists() and target.suffix == ".html":
            check(fragment in parse(target).ids, f"missing fragment in {source.name}: {href}")

root_text = (ROOT / "index.html").read_text(encoding="utf-8")
check("The tax is rarely the problem" not in root_text, "old categorical root headline remains")
check('<p class="value">$0</p>' not in root_text, "old categorical conversion-tax KPI remains")
check("acceptance-382482c0/index.html" in root_text, "root does not link acceptance page")
check("playbook-c1d73006/costs.html" in root_text, "root does not link full published-input ladder")
check("unlock M01 single-wire conversion" not in root_text, "automatic transfer-unlock wording remains")
readme = (ROOT / "README.md").read_text(encoding="utf-8")
check("typically `0.30%–1.50%` modelled" not in readme, "unsupported spread band remains in README")
check("Root `index.html` is a category hub generated by `ladder/build.py`" not in readme,
      "stale root generator instructions remain")
check("verification-3347ca0a/build.py" in readme, "correct root generator not documented")

# Independently verify the complete cost-ledger shape and source coverage.
with (ROOT / "playbook-c1d73006/data/costs.csv").open(encoding="utf-8", newline="") as f:
    costs = list(csv.DictReader(f))
check(len(costs) == 680, f"expected 680 cost rows, got {len(costs)}")
methods = sorted({r["method"] for r in costs})
check(len(methods) == 17, f"expected 17 methods, got {len(methods)}")
expected_tiers = list(range(10000, 400001, 10000))
for method in methods:
    rows = [r for r in costs if r["method"] == method]
    tiers = sorted(int(r["amount_usd"]) for r in rows)
    check(tiers == expected_tiers, f"{method}: missing or duplicate amount tier")
    for r in rows:
        check(bool(r["source_urls"].strip()), f"{method} {r['amount_usd']}: source blank")
        check(all(u.startswith("https://") for u in r["source_urls"].split()),
              f"{method} {r['amount_usd']}: non-HTTPS source")
        for field in ("bank_of_china_inputs_usd", "hsbc_china_inputs_usd"):
            if r[field]:
                check(float(r[field]) >= 0, f"{method} {r['amount_usd']}: negative estimate")
            else:
                check(bool(r["flag_for_blank"]), f"{method} {r['amount_usd']}: blank without flag")

if failures:
    print(f"FAIL · {checks} checks · {len(failures)} failures", file=sys.stderr)
    for failure in failures:
        print(" - " + failure, file=sys.stderr)
    sys.exit(1)
print(f"PASS · {checks} checks · 8 findings · 7 flags · 680 cost rows / 40 tiers / 17 methods")
